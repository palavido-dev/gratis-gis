WEAK = {"password", "devpassword", "admin", "changeme", "secret", "gratisgis"}


def boot_dir() -> Path:
    return Path(os.environ.get("BOOT_DIR", "/boot"))


def sh_quote(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"


def rand(n: int = 32) -> str:
    # Letters and digits only, so the env file and the database URL
    # stay easy to source.
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
    return "".join(secrets.choice(alphabet) for _ in range(n))


def encryption_key() -> str:
    return base64.b64encode(secrets.token_bytes(32)).decode("ascii")


def lan_ips_from_fib(text: str) -> list[str]:
    """Pull private IPv4 addresses out of /proc/net/fib_trie text."""
    found: list[str] = []
    for match in re.finditer(r"(\d{1,3}(?:\.\d{1,3}){3})", text):
        ip = match.group(1)
        parts = [int(p) for p in ip.split(".")]
        if any(p > 255 for p in parts):
            continue
        if ip.startswith("127.") or ip.startswith("169.254.") or ip == "0.0.0.0":
            continue
        if ip.startswith("192.168.") or ip.startswith("10."):
            if ip not in found:
                found.append(ip)
            continue
        # 172.16.0.0/12, but skip the usual Docker bridges.
        if parts[0] == 172 and 16 <= parts[1] <= 31:
            if parts[1] in (17, 18, 19):
                continue
            if ip not in found:
                found.append(ip)
    return found


def detect_lan_ip() -> str:
    explicit = os.environ.get("GRATIS_DETECT_FIB", "")
    blobs = []
    if explicit:
        blobs.append(explicit)
    for path in ("/proc/1/net/fib_trie", "/proc/net/fib_trie"):
        try:
            blobs.append(Path(path).read_text(encoding="utf-8", errors="replace"))
        except OSError:
            continue
    for blob in blobs:
        ips = lan_ips_from_fib(blob)
        if ips:
            return ips[0]
    return "127.0.0.1"


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = [
        "# Generated by infra/nas-init.py. Random per install.",
        "# Do not commit this file. It lives on the Docker volume.",
    ]
    for key, value in values.items():
        lines.append(f"{key}={sh_quote(value)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    path.chmod(0o644)


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if len(value) >= 2 and value[0] == "'" and value[-1] == "'":
            value = value[1:-1].replace("'\"'\"'", "'")
        values[key] = value
    return values


def org_mappers() -> list[dict]:
    def one(name: str) -> dict:
        return {
            "name": name,
            "protocol": "openid-connect",
            "protocolMapper": "oidc-usermodel-attribute-mapper",
            "consentRequired": False,
            "config": {
                "userinfo.token.claim": "true",
                "user.attribute": name,
                "id.token.claim": "true",
                "access.token.claim": "true",
                "claim.name": name,
                "jsonType.label": "String",
            },
        }

    return [one("org"), one("org_role")]


